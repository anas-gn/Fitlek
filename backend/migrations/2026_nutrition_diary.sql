CREATE TABLE IF NOT EXISTS client_meals (
  userID BIGINT UNSIGNED NOT NULL,
  id VARCHAR(80) NOT NULL,
  mealDate DATE NOT NULL,
  mealType VARCHAR(16) NOT NULL,
  consumedAt VARCHAR(35) NOT NULL,
  payload JSON NOT NULL,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (userID,id),
  INDEX client_meal_day (userID,mealDate),
  CONSTRAINT fk_client_meals_user FOREIGN KEY (userID) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS client_nutrition_goals (
  userID BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  goals JSON NOT NULL,
  CONSTRAINT fk_nutrition_goals_user FOREIGN KEY (userID) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
