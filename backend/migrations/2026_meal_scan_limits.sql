CREATE TABLE IF NOT EXISTS meal_scan_settings (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  dailyLimit INT UNSIGNED NOT NULL DEFAULT 3
) ENGINE=InnoDB;
