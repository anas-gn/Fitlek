CREATE TABLE IF NOT EXISTS meal_scan_clients (
  userID INT NOT NULL PRIMARY KEY,
  dailyLimit INT UNSIGNED NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS meal_scan_usage (
  userID INT NOT NULL,
  scanDay DATE NOT NULL,
  used INT UNSIGNED NOT NULL DEFAULT 0,
  bonus INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (userID, scanDay)
) ENGINE=InnoDB;
