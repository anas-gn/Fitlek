CREATE TABLE IF NOT EXISTS client_nutrition_plans (
  userID BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  plan JSON NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'active',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  startedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX nutrition_active (status,userID),
  CONSTRAINT fk_nutrition_plan_user FOREIGN KEY (userID) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
